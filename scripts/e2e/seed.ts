/**
 * Seeds the ephemeral e2e Firefly (started by scripts/e2e/up.sh) with the
 * scenario ledger, then writes .e2e/id-map.json and .e2e/config.yaml.
 *
 * Safety: credentials come ONLY from .e2e/env (parsed explicitly; no dotenv
 * search path, no process.env fallback), the URL must be 127.0.0.1 on the
 * port recorded in .e2e/state.json, and the token must belong to the e2e user.
 *
 * Reuse: if the database carries this scenario's marker tag, exit 0 without
 * touching anything. Data without the marker, or a marker for a different
 * scenario hash, aborts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';
import * as yaml from 'js-yaml';
import { FireflyClientWithCerts } from '../../src/api/firefly-client-with-certs.js';
import { assertLocalFirefly } from '../../test-harness/safety.js';
import { buildScenarioConfig } from '../../test-harness/scenario/config.js';
import { markerTag } from '../../test-harness/scenario/hash.js';
import {
    createMarkerTag,
    inspectSeedState,
    seedScenario,
} from '../../test-harness/seed/seed-scenario.js';

export const E2E_EMAIL = 'e2e@btk.invalid';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const STATE_DIR = path.join(ROOT, '.e2e');
const ENV_PATH = path.join(STATE_DIR, 'env');
const STATE_PATH = path.join(STATE_DIR, 'state.json');
const ID_MAP_PATH = path.join(STATE_DIR, 'id-map.json');
const CONFIG_PATH = path.join(STATE_DIR, 'config.yaml');

const log = (msg: string) => process.stderr.write(`[e2e:seed] ${msg}\n`);

function fail(msg: string): never {
    process.stderr.write(`[e2e:seed] ERROR: ${msg}\n`);
    process.exit(1);
}

function writeAtomic(file: string, content: string, mode = 0o600): void {
    const tmp = `${file}.tmp`;
    fs.writeFileSync(tmp, content, { mode });
    fs.renameSync(tmp, file);
}

async function main(): Promise<void> {
    if (!fs.existsSync(ENV_PATH) || !fs.existsSync(STATE_PATH)) {
        fail(`${ENV_PATH} / ${STATE_PATH} missing; run \`npm run e2e:up\` first`);
    }
    const env = dotenv.parse(fs.readFileSync(ENV_PATH));
    const state = JSON.parse(fs.readFileSync(STATE_PATH, 'utf8')) as { port: number; url: string };
    const url = env.FIREFLY_API_URL;
    const token = env.FIREFLY_API_TOKEN;
    if (!url || !token) fail(`${ENV_PATH} lacks FIREFLY_API_URL or FIREFLY_API_TOKEN`);

    assertLocalFirefly(url, state.port);
    if (url !== state.url) fail(`.e2e/env URL ${url} does not match state.json ${state.url}`);

    const client = new FireflyClientWithCerts({ BASE: `${url}/api`, TOKEN: token });

    const user = await client.about.getCurrentUser();
    const email = user.data.attributes.email;
    if (email !== E2E_EMAIL) fail(`token belongs to '${email}', expected ${E2E_EMAIL}`);

    const seedState = await inspectSeedState(client);
    if (seedState.kind === 'seeded') {
        if (!fs.existsSync(ID_MAP_PATH) || !fs.existsSync(CONFIG_PATH)) {
            fail(
                `marker ${seedState.marker} present but .e2e/id-map.json or config.yaml is missing; ` +
                    'run `npm run e2e:down` and start again'
            );
        }
        log(`marker ${seedState.marker} present: reusing the seeded database`);
        return;
    }
    if (seedState.kind === 'foreign') {
        fail(
            `${seedState.reason}.\n` +
                '  The seeder only seeds an empty database. Run `npm run e2e:down` ' +
                '(the database is on tmpfs) and then `npm run test:e2e` or `npm run e2e:up && npm run e2e:seed`.'
        );
    }

    const started = Date.now();
    log(`seeding ${url} (marker ${markerTag()})`);
    const idMap = await seedScenario(client, { log });

    writeAtomic(ID_MAP_PATH, `${JSON.stringify(idMap, null, 2)}\n`);
    const header =
        '# Generated by scripts/e2e/seed.ts from test-harness/scenario/config.ts. Do not edit.\n';
    writeAtomic(CONFIG_PATH, header + yaml.dump(buildScenarioConfig(idMap), { lineWidth: -1 }));

    // Last: the marker is what makes a database reusable
    const marker = await createMarkerTag(client);
    log(`done in ${((Date.now() - started) / 1000).toFixed(1)}s; marker ${marker}`);
}

main().catch(err => {
    fail(err instanceof Error ? err.message : String(err));
});
